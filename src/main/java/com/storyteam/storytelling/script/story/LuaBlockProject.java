package com.storyteam.storytelling.script.story;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;

/** A small, linear visual story. Generated Lua remains the executable source. */
public final class LuaBlockProject {
   public enum Kind { SPEECH, WAIT_F8, WAIT_TICKS, ANCHOR, BLACKOUT }
   public record Block(Kind kind, String value) { }

   private static final Gson GSON = new Gson();
   private final int id;
   private final List<Block> blocks = new ArrayList<>();
   private String generatedHash = "";

   private LuaBlockProject(int id) { this.id = id; }
   public int id() { return id; }
   public List<Block> blocks() { return blocks; }

   public static LuaBlockProject create(int id) {
      if (id <= 0) throw new IllegalArgumentException("Story ID must be positive");
      return new LuaBlockProject(id);
   }

   public static LuaBlockProject open(int id) throws IOException {
      LuaBlockProject project = create(id);
      Path directory = StoryWorkspace.root().resolve("projects");
      Files.createDirectories(directory);
      Path file = directory.toRealPath().resolve(id + ".json");
      if (!Files.exists(file)) return project;
      if (Files.isSymbolicLink(file)) throw new IOException("Project symlink is not allowed");
      JsonObject root = JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)).getAsJsonObject();
      if (root.get("id").getAsInt() != id || root.get("format").getAsInt() != 1)
         throw new IOException("Unsupported block project format");
      project.generatedHash = root.has("generatedHash") ? root.get("generatedHash").getAsString() : "";
      for (var element : root.getAsJsonArray("blocks")) {
         JsonObject block = element.getAsJsonObject();
         project.blocks.add(new Block(Kind.valueOf(block.get("kind").getAsString()), block.get("value").getAsString()));
      }
      return project;
   }

   public String generate() {
      StringBuilder lua = new StringBuilder("-- Generated by Storytelling block editor. Edit the project to regenerate.\n")
         .append("story(").append(id).append(")\n")
         .append("part(\"main\")\n")
         .append("speaker(1, \"Рассказчик\")\n");
      for (Block block : blocks) {
         switch (block.kind()) {
            case SPEECH -> lua.append("speech(1, ").append(quoted(block.value())).append(")\n");
            case WAIT_F8 -> lua.append("wait_f8()\n");
            case WAIT_TICKS -> {
               int ticks = Integer.parseInt(block.value());
               if (ticks < 1 || ticks > 72000) throw new IllegalArgumentException("Ожидание: 1–72000 тиков");
               lua.append("wait_ticks(").append(ticks).append(")\n");
            }
            case ANCHOR -> {
               if (!block.value().matches("[A-Za-z][A-Za-z0-9_]{0,63}"))
                  throw new IllegalArgumentException("Якорь: латинские буквы, цифры и _");
               lua.append("anchor(").append(quoted(block.value())).append(")\n");
            }
            case BLACKOUT -> {
               int ticks = Integer.parseInt(block.value());
               if (ticks < 1 || ticks > 1200) throw new IllegalArgumentException("Затемнение: 1–1200 тиков");
               lua.append("blackout(").append(ticks).append(")\n");
            }
         }
      }
      if (blocks.isEmpty()) throw new IllegalArgumentException("Добавьте хотя бы один блок");
      String source = lua.toString();
      LuaStory.parse(source, id + ".lua");
      return source;
   }

   public void save() throws IOException {
      String source = generate();
      Path scripts = StoryWorkspace.scripts();
      Files.createDirectories(scripts);
      Path script = scripts.toRealPath().resolve(id + ".lua");
      if (Files.isSymbolicLink(script)) throw new IOException("Lua-файл является ссылкой");
      if (Files.exists(script)) {
         if (generatedHash.isEmpty()) throw new IOException("Lua-файл уже существует; проект не будет его перезаписывать");
         if (!generatedHash.equals(hash(Files.readString(script, StandardCharsets.UTF_8))))
            throw new IOException("Lua-файл изменён вручную; проект не будет его перезаписывать");
      }
      StoryFileWriter.write(script, source, true);
      generatedHash = hash(source);
      JsonObject root = new JsonObject();
      root.addProperty("format", 1);
      root.addProperty("id", id);
      root.addProperty("generatedHash", generatedHash);
      JsonArray entries = new JsonArray();
      for (Block block : blocks) {
         JsonObject entry = new JsonObject();
         entry.addProperty("kind", block.kind().name());
         entry.addProperty("value", block.value());
         entries.add(entry);
      }
      root.add("blocks", entries);
      Path projects = StoryWorkspace.root().resolve("projects");
      Files.createDirectories(projects);
      StoryFileWriter.write(projects.toRealPath().resolve(id + ".json"), GSON.toJson(root), true);
   }

   private static String quoted(String value) {
      return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"")
         .replace("\r", "\\r").replace("\n", "\\n") + "\"";
   }

   private static String hash(String value) {
      try { return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(value.getBytes(StandardCharsets.UTF_8))); }
      catch (NoSuchAlgorithmException impossible) { throw new IllegalStateException(impossible); }
   }
}
