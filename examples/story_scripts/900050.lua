-- Сквозная проверка: NPC, камера, выбор, квест, предмет и восстановление шага.
-- Тестовый мир: ровный проход от -3.5 -60 8.5 до 0.5 -60 8.5.
story(900050)
local reg = npc{ key = "chapter_guide", model = "reg.gltf", name = "Регир", width = 0.6, height = 2.0 }

part("main")
reg:spawn(-3.5, -60, 8.5)
reg:speaker(1)
reg:look("player", "auto")
quest_create("chapter_900050", "Встреча с Региром", "Поговорите с проводником и сообщите о выборе.")
quest_source("chapter_900050", "Регир")
quest_task("chapter_900050", "meet", "Поговорить с Региром")
quest_subtask("chapter_900050", "meet", "listen", "Выслушать проводника")
quest_subtask("chapter_900050", "meet", "decide", "Принять решение", true)
quest_task("chapter_900050", "report", "Сообщить о результате")
quest_subtask("chapter_900050", "report", "message", "Написать «готово» в чат")
quest_start("chapter_900050")
hint("Нажмите F8 после реплики Регира", 120)
speech(1, "Я покажу путь. Нажми F8, чтобы посмотреть на меня поближе.")
wait_f8()
reg:camera(45, 30, 1.6)
quest_subtask_complete("chapter_900050", "meet", "listen")
speech(1, "Теперь выбери, пойдём ли мы вместе.")
wait_f8()
choice("route", "Как поступим?", "Пойти вместе", "Остаться здесь")
var_if("route", 1, "follow", "stay")

anchor("stay")
speech(1, "Хорошо, я останусь здесь.")
wait_f8()
goto_anchor("route_end")

anchor("follow")
reg:move(0.5, -60, 8.5, 0.7)
speech(1, "Мы дошли до точки. Вот тебе яблоко на дорогу.")
wait_f8()

anchor("route_end")
quest_subtask_complete("chapter_900050", "meet", "decide")
give_item("minecraft:apple", 1)
speech(1, "Яблоко выдано. Можно выйти в меню и вернуться до следующего F8: повторной выдачи не должно быть.")
wait_f8()
hint("Напишите «готово» в обычный чат", 160)
wait_chat("готово")
quest_subtask_complete("chapter_900050", "report", "message")
speech(1, "Задание завершено. Проверь журнал клавишей J.")
wait_f8()
