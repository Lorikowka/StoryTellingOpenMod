-- Проверка восстановления движения NPC после выхода в меню.
-- После F8 выйдите в меню, пока Регир идёт, затем вернитесь в тот же мир.
story(900061)
local reg = npc{key = "route_tester", model = "reg.gltf", name = "Регир", width = 0.6, height = 2.0}

part("main")
reg:spawn(0.5, -59, 8.5)
reg:speaker(1)
speech(1, "После F8 я медленно пойду к точке. Выйди в меню, пока я ещё иду.")
wait_f8()
reg:move(5.5, -60, 9.5, 0.1)
speech(1, "Маршрут завершён после возвращения в мир.")
wait_f8()
